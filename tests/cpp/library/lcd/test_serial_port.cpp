/**
 * @file test_serial_port.cpp
 * @brief Unit tests of the serial port helpers (src/library/lcd/serial_port), on all platforms.
 */

#include <string>

#include <gtest/gtest.h>

#include "library/lcd/serial_port.h"

namespace {

ListPortInfo parse(const std::string &instance_id)
{
    ListPortInfo info;
    parse_device_instance_id(instance_id, info);
    return info;
}

}  // namespace

/** @brief USB device with a serial number (Turing Smart Screen 3.5" revision A). */
TEST(SerialPort, InstanceIdUsbWithSerialNumber)
{
    const ListPortInfo info = parse("USB\\VID_1A86&PID_5722\\USB35INCHIPSV2");
    EXPECT_EQ(info.vid, 0x1a86);
    EXPECT_EQ(info.pid, 0x5722);
    EXPECT_EQ(info.serial_number, "USB35INCHIPSV2");
}

/** @brief Serial numbers with other characters than letters and digits are kept (revision B: "2017-2-25"). */
TEST(SerialPort, InstanceIdSerialNumberWithDashes)
{
    EXPECT_EQ(parse("USB\\VID_1A86&PID_5722\\2017-2-25").serial_number, "2017-2-25");
}

/** @brief Interface of a composite device: the ID generated by Windows is not a serial number. */
TEST(SerialPort, InstanceIdCompositeDevice)
{
    const ListPortInfo info = parse("USB\\VID_0525&PID_A4A7&MI_00\\6&2C1F2B9&0&0000");
    EXPECT_EQ(info.vid, 0x0525);
    EXPECT_EQ(info.pid, 0xa4a7);
    EXPECT_EQ(info.serial_number, "");
}

/** @brief Lower case hexadecimal digits are accepted. */
TEST(SerialPort, InstanceIdLowerCase)
{
    const ListPortInfo info = parse("USB\\VID_1a86&PID_fe0c\\AD1234");
    EXPECT_EQ(info.vid, 0x1a86);
    EXPECT_EQ(info.pid, 0xfe0c);
    EXPECT_EQ(info.serial_number, "AD1234");
}

/** @brief FTDI driver: identifiers separated by '+'. */
TEST(SerialPort, InstanceIdFtdi)
{
    const ListPortInfo info = parse("FTDIBUS\\VID_0403+PID_6001+A50285BIA\\0000");
    EXPECT_EQ(info.vid, 0x0403);
    EXPECT_EQ(info.pid, 0x6001);
    EXPECT_EQ(info.serial_number, "A50285BIA");
}

/** @brief Ports that are not USB devices (motherboard port, Bluetooth) have no USB information. */
TEST(SerialPort, InstanceIdNotUsb)
{
    for (const char *id: {"ACPI\\PNP0501\\0", "BTHENUM\\{00001101-0000-1000-8000-00805F9B34FB}_LOCALMFG&0002\\7&1"}) {
        const ListPortInfo info = parse(id);
        EXPECT_FALSE(info.vid.has_value()) << id;
        EXPECT_FALSE(info.pid.has_value()) << id;
        EXPECT_EQ(info.serial_number, "") << id;
    }
}
